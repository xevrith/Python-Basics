# Calculator 

class Calculator:
    @staticmethod
    def add(a,b):
        return a + b 

    @staticmethod
    def subtract(a,b):
        return a - b

    @staticmethod
    def multiplhy(a,b):
        return a * b 


print(Calculator.add(2,4))
print(Calculator.subtract(4,4))
print(Calculator.multiplhy(2,4))